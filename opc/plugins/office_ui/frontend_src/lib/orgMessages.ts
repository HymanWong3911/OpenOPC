export type OrgMessage = (source: string, params?: Record<string, string | number>) => string

function interpolate(source: string, params?: Record<string, string | number>): string {
  if (!params) return source
  return source.replace(/\{(\w+)\}/g, (match, key: string) => Object.hasOwn(params, key) ? String(params[key]) : match)
}

const en: OrgMessage = (source, params) => interpolate(source, params)
const zh: OrgMessage = (source, params) => interpolate(Object.hasOwn(ORG_ZH_MESSAGES, source) ? ORG_ZH_MESSAGES[source] : source, params)

/** Stable function identities let memoized columns update when the locale changes. */
export function orgMessages(locale: Locale): OrgMessage {
  return locale === 'zh-CN' ? zh : en
}
