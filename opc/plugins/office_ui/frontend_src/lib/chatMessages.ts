export type ChatText = (english: string, values?: Record<string, string | number>) => string

/** Translate only builtin chat chrome; caller-owned content passes through unchanged. */
export function useChatText(): ChatText {
  const uiText = useUiText()
  return useCallback((english, values) => {
    const text = uiText(english, CHAT_MESSAGES[english] ?? english)
    return text.replace(/\{(\w+)\}/g, (token, name: string) => String(values?.[name] ?? token))
  }, [uiText])
}

export function localizeAttachmentError(error: string, tr: ChatText): string {
  const oversized = /^Too large \((.+)\)$/.exec(error)
  return oversized ? tr('Too large ({size})', { size: oversized[1] }) : tr(error)
}

export function localizeSystemLabel(label: string, tr: ChatText): string {
  const delegation = /^Delegating to (.+)$/.exec(label)
  return delegation ? tr('Delegating to {agent}', { agent: delegation[1] }) : tr(label)
}

export function localizeAcceptanceSummary(summary: string, tr: ChatText): string {
  const generated = /^(\d+)\/(\d+) acceptance checks met$/.exec(summary)
  return generated ? tr('{met}/{total} acceptance checks met', { met: generated[1], total: generated[2] }) : summary
}

export function localizeExternalTeamSummary(summary: ExternalTeamActivitySummary | undefined, tr: ChatText): string {
  const text = externalTeamSummaryText(summary)
  const failed = /^(\d+) members · Team error$/.exec(text)
  if (failed) return tr('{members} members · Team error', { members: failed[1] })
  const complete = /^(\d+) members · (\d+)\/(\d+) tasks completed$/.exec(text)
  if (complete) return tr('{members} members · {done}/{total} tasks completed', { members: complete[1], done: complete[2], total: complete[3] })
  const active = /^(\d+) members · (\d+) active( · Leader synthesizing)?$/.exec(text)
  if (active) return tr(active[3] ? '{members} members · {active} active · Leader synthesizing' : '{members} members · {active} active', { members: active[1], active: active[2] })
  return tr(text)
}
