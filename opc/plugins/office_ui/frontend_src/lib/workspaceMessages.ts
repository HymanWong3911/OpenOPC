export function workspaceText(english: string, locale: Locale): string {
  if (locale !== 'zh-CN') return english
  const key = english.trim()
  if (!Object.prototype.hasOwnProperty.call(WORKSPACE_COPY, key)) {
    const agents = key.match(/^(\d+) agents working$/)
    if (agents) return `${agents[1]} 个智能体工作中`
    const tool = key.match(/^Running (.+)$/)
    if (tool) return `正在运行 ${tool[1]}`
    const time = key.match(/^(\d+)([smhd])(?: ago)?$/)
    if (time) return `${time[1]}${({s:'秒',m:'分钟',h:'小时',d:'天'} as Record<string,string>)[time[2]]}前`
    const mode = key.match(/^company\/(.+)$/)
    if (mode) return `公司 / ${mode[1] === 'corporate' ? '企业' : mode[1]}`
    const success = key.match(/^(Saved|Created|Loaded|Deleted) "(.*)"$/)
    if (success) return `${({Saved:'已保存',Created:'已创建',Loaded:'已加载',Deleted:'已删除'} as Record<string,string>)[success[1]]}「${success[2]}」`
    const failure = key.match(/^(Save|Create|Load|Delete) failed: (.*)$/)
    if (failure) return `${({Save:'保存',Create:'创建',Load:'加载',Delete:'删除'} as Record<string,string>)[failure[1]]}失败：${failure[2]}`
    return english
  }
  return `${english.match(/^\s*/)?.[0] ?? ''}${WORKSPACE_COPY[key]}${english.match(/\s*$/)?.[0] ?? ''}`
}

export function useWorkspaceText(): (english: string) => string {
  const { locale } = useI18n()
  return useCallback((english: string) => workspaceText(english, locale), [locale])
}
